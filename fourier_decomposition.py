import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# ==========================================
# STEP 1: Generate & Save Data (Self-Contained)
# ==========================================
time_points = np.arange(0, 24.25, 0.25) # 0 to 24 hrs in 15-min steps
np.random.seed(42)
data = {'Time': time_points}

for i in range(1, 11):
    peak_time = np.random.normal(2.0, 0.2)
    peak_height = np.random.normal(10.0, 1.0)
    curve = 1.0 + peak_height * np.exp(-0.4 * (time_points - peak_time)**2)
    noise = np.random.normal(0, 0.6, len(time_points))
    data[f'Subject_{i}'] = np.maximum(1.0, curve + noise)

df = pd.DataFrame(data)
df.to_csv('magic_mushroom_data.csv', index=False)

# ==========================================
# STEP 2: Load Data & Calculate Grand Average
# ==========================================
time = df['Time'].values
subject_columns = [col for col in df.columns if col != 'Time']
data_matrix = df[subject_columns].values

# Grand average across the 10 subjects
grand_avg = data_matrix.mean(axis=1)

# ==========================================
# STEP 3: Fourier Decomposition via FFT
# ==========================================
fft_vals = np.fft.rfft(grand_avg) # Real Fast Fourier Transform for time-series

# Keep only the lowest frequency components (smooth macro-trends)
n_components = 6  # Number of sinusoidal components to keep
fft_filtered = np.zeros_like(fft_vals)
fft_filtered[:n_components] = fft_vals[:n_components]

# Reconstruct the signal using Inverse Real FFT
reconstructed_signal = np.fft.irfft(fft_filtered, n=len(grand_avg))

# ==========================================
# STEP 4: Plotting the Results
# ==========================================
plt.figure(figsize=(10, 6))

# Plot individual subject runs faintly in the background
for col in subject_columns:
    plt.plot(time, df[col], color='lightgray', alpha=0.4, linewidth=1)

# Plot grand average points and Fourier reconstruction line
plt.scatter(time, grand_avg, color='black', s=15, label='Grand Average Data', zorder=3)
plt.plot(time, reconstructed_signal, color='purple', linewidth=3, label=f'Fourier Reconstruction ({n_components} Sinusoids)', zorder=4)

plt.title('Magic Mushroom Time-Series: Fourier Decomposition & Sinusoidal Reconstruction', fontsize=12)
plt.xlabel('Time (Hours)', fontsize=10)
plt.ylabel('Susceptibility to Visual Illusion (Effect Strength)', fontsize=10)
plt.legend(loc='upper right')
plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()
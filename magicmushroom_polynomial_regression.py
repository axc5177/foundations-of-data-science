import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# STEP 1: Load the CSV Data
time_points = np.arange(0, 24.25, 0.25) # 0 to 24 hrs in 15-min steps
np.random.seed(42)
data = {'Time': time_points}

for i in range(1, 11):
    peak_time = np.random.normal(2.0, 0.2)
    peak_height = np.random.normal(10.0, 1.0)
    # Bi-exponential curve approximation for the drug effect
    curve = 1.0 + peak_height * np.exp(-0.4 * (time_points - peak_time)**2)
    noise = np.random.normal(0, 0.6, len(time_points))
    data[f'Subject_{i}'] = np.maximum(1.0, curve + noise)

df = pd.DataFrame(data)
df.to_csv('magic_mushroom_data.csv', index=False)

# STEP 2: Prepare Data & Grand Average
time = df['Time'].values
subject_columns = [col for col in df.columns if col != 'Time']
data_matrix = df[subject_columns].values # Shape: (97 timepoints, 10 subjects)

# Grand average across the 10 subjects
grand_avg = data_matrix.mean(axis=1)

# STEP 3: Polynomial Fit (e.g., 3rd Order)
poly_degree = 3
original_coeffs = np.polyfit(time, grand_avg, deg=poly_degree)
original_poly_func = np.poly1d(original_coeffs)
original_fit_y = original_poly_func(time)

# STEP 4: Bootstrapping & Plotting
plt.figure(figsize=(10, 6))

# Plot the 10 original subject runs faintly in the background
for col in subject_columns:
    plt.plot(time, df[col], color='lightgray', alpha=0.4, linewidth=1)

# Run Bootstrap (e.g., 150 iterations)
n_bootstraps = 150
n_subjects = len(subject_columns)

for _ in range(n_bootstraps):
    # Sample subjects with replacement
    sampled_indices = np.random.choice(n_subjects, size=n_subjects, replace=True)
    bootstrap_matrix = data_matrix[:, sampled_indices]

    # Calculate bootstrap grand average and fit polynomial
    boot_avg = bootstrap_matrix.mean(axis=1)
    boot_coeffs = np.polyfit(time, boot_avg, deg=poly_degree)
    boot_poly_func = np.poly1d(boot_coeffs)

    # Plot ghosty transparent line
    plt.plot(time, boot_poly_func(time), color='skyblue', alpha=0.15, linewidth=1)

# Plot the grand average data points and the bold original fit line
plt.scatter(time, grand_avg, color='black', s=15, label='Grand Average Data', zorder=3)
plt.plot(time, original_fit_y, color='red', linewidth=3, label=f'Order {poly_degree} Polynomial Fit', zorder=4)

plt.title('Magic Mushroom Time-Series: Polynomial Regression & Bootstrap Stability', fontsize=12)
plt.xlabel('Time (Hours)', fontsize=10)
plt.ylabel('Susceptibility to Visual Illusion (Effect Strength)', fontsize=10)
plt.legend(loc='upper right')
plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()
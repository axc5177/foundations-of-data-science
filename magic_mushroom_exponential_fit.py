import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.optimize import curve_fit

time_points = np.arange(0, 24.25, 0.25) # 0 to 24 hrs in 15-min steps
np.random.seed(42)
data = {'Time': time_points}

for i in range(1, 11):
    peak_time = np.random.normal(2.0, 0.2)
    peak_height = np.random.normal(10.0, 1.0)
    curve = 1.0 + peak_height * np.exp(-0.4 * (time_points - peak_time)**2)
    noise = np.random.normal(0, 0.6, len(time_points))
    data[f'Subject_{i}'] = np.maximum(1.0, curve + noise)

df = pd.DataFrame(data)
time = df['Time'].values
subject_columns = [col for col in df.columns if col != 'Time']
data_matrix = df[subject_columns].values
grand_avg = data_matrix.mean(axis=1)

# Models a rapid rise and a gradual exponential decay back to baseline (1.0)
def bi_exponential(t, amp, ka, ke, baseline):
    # Prevents runtime warnings for extreme values
    t = np.maximum(t, 0)
    return baseline + amp * (np.exp(-ke * t) - np.exp(-ka * t))

# Initial parameter guesses: [amplitude, absorption rate, elimination rate, baseline]
initial_guess = [10.0, 1.5, 0.3, 1.0]

# Fit to the original grand average
popt, _ = curve_fit(bi_exponential, time, grand_avg, p0=initial_guess, bounds=(0, [50, 10, 5, 5]))
original_fit_y = bi_exponential(time, *popt)

plt.figure(figsize=(10, 6))

# Plot individual subject runs faintly in the background
for col in subject_columns:
    plt.plot(time, df[col], color='lightgray', alpha=0.4, linewidth=1)

# Run Bootstrap (e.g., 150 iterations)
n_bootstraps = 150
n_subjects = len(subject_columns)

for _ in range(n_bootstraps):
    sampled_indices = np.random.choice(n_subjects, size=n_subjects, replace=True)
    bootstrap_matrix = data_matrix[:, sampled_indices]
    boot_avg = bootstrap_matrix.mean(axis=1)

    try:
        boot_popt, _ = curve_fit(bi_exponential, time, boot_avg, p0=popt, bounds=(0, [50, 10, 5, 5]))
        boot_fit_y = bi_exponential(time, *boot_popt)
        plt.plot(time, boot_fit_y, color='orange', alpha=0.15, linewidth=1)
    except RuntimeError:
        # Skip if a bootstrap sample fails to converge
        continue

# Plot grand average data points and the bold exponential fit lines
plt.scatter(time, grand_avg, color='black', s=15, label='Grand Average Data', zorder=3)
plt.plot(time, original_fit_y, color='red', linewidth=3, label='Bi-Exponential Fit', zorder=4)

plt.title('Magic Mushroom Time-Series: Bi-Exponential Pharmacokinetic Fit & Bootstrap Stability', fontsize=12)
plt.xlabel('Time (Hours)', fontsize=10)
plt.ylabel('Susceptibility to Visual Illusion (Effect Strength)', fontsize=10)
plt.legend(loc='upper right')
plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()